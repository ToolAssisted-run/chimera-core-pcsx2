#!/usr/bin/env python3
# Turns PCSX2's patch collection into a table the core carries inside itself.
#
# WHAT THIS IS FOR (chimera#371, user-decided 2026-10-25). PCSX2/pcsx2_patches
# is the collection upstream ships as patches.zip: per game, the changes the
# community made to its code - a widescreen picture, 60 frames a second, no
# interlacing, no blur. Upstream offers the widescreen and no-interlacing ones
# behind two switches and the rest in a list of patches. Here every one of
# them is a setting of its own, off unless the project turns it on
# ("Use Custom Patch: Enable ..."), so a movie cites exactly the patches it
# was made with.
#
# WHY IT IS COMPILED IN. A core has no resources directory and nobody mounts
# an emulator's patch zip, so the files are carried in the core as the game
# database is (waterbox/gen-gamedb.py), and the package a movie cites pins
# them. Patch.cpp reads them through chimera_pnach_text (patch 0030), under the
# names it would have looked for in the zip: SERIAL_CRC.pnach, then CRC.pnach.
#
# THE TERMS. The collection carries no licence file. The owner decided to ship
# it regardless, crediting it (waterbox/package-licenses.json).
#
# A PATCH WITH NO NAME IS AN ERROR. Upstream turns on every patch that is not
# in a named group, with no way to turn it off; here a patch is on only when
# its setting is, and a patch with no name has no setting. None exists today,
# and a collection update that adds one stops the build and names the file.
#
# Usage: gen-pnach.py <pcsx2_patches/patches> <output .cpp>
import os
import sys

src_dir, out_path = sys.argv[1], sys.argv[2]


def c_string(text):
    """A C string literal for the bytes of `text`, split so no line is long."""
    data = text.encode("utf-8")
    out, line = [], []
    for b in data:
        if b == 0x5C:
            line.append("\\\\")
        elif b == 0x22:
            line.append('\\"')
        elif b == 0x0A:
            line.append("\\n")
            out.append('"' + "".join(line) + '"')
            line = []
            continue
        elif b == 0x09:
            line.append("\\t")
        elif 0x20 <= b < 0x7F and b != 0x3F:   # '?' escaped: no trigraphs
            line.append(chr(b))
        else:
            line.append("\\%03o" % b)
    if line or not out:
        out.append('"' + "".join(line) + '"')
    return "\n\t\t".join(out)


def unnamed_patch(text):
    """True when a patch line comes before the first [named] group."""
    for raw in text.split("\n"):
        line = raw.split("//", 1)[0].strip()
        if line.startswith("[") and line.endswith("]"):
            return False
        if line.startswith("patch=") or line.startswith("dpatch="):
            return True
    return False


names = sorted(n for n in os.listdir(src_dir) if n.endswith(".pnach"))
if not names:
    sys.exit(f"gen-pnach: no .pnach files in {src_dir}")

entries = []
for name in names:
    with open(os.path.join(src_dir, name), "rb") as f:
        text = f.read().decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")
    if unnamed_patch(text):
        sys.exit(f"gen-pnach: {name} has a patch outside a named group, which no setting could turn off")
    entries.append((name, text))

with open(out_path, "w", encoding="ascii", newline="\n") as out:
    out.write("// Generated by waterbox/gen-pnach.py from PCSX2/pcsx2_patches. Do not edit.\n")
    out.write("#include <cstddef>\n#include <cstring>\n\n")
    out.write("namespace {\nstruct Pnach { const char* name; const char* text; };\n")
    out.write("const Pnach kPnach[] = {\n")
    for name, text in entries:
        out.write("\t{ " + c_string(name) + ",\n\t\t" + c_string(text) + " },\n")
    out.write("};\n}\n\n")
    out.write("extern \"C\" size_t chimera_pnach_count(void) { return sizeof(kPnach) / sizeof(kPnach[0]); }\n\n")
    out.write("// The text of the file of that name, or nullptr. The table is in name order.\n")
    out.write("extern \"C\" const char* chimera_pnach_text(const char* name)\n{\n")
    out.write("\tsize_t lo = 0, hi = sizeof(kPnach) / sizeof(kPnach[0]);\n")
    out.write("\twhile (lo < hi)\n\t{\n")
    out.write("\t\tconst size_t mid = lo + (hi - lo) / 2;\n")
    out.write("\t\tconst int c = std::strcmp(kPnach[mid].name, name);\n")
    out.write("\t\tif (c == 0)\n\t\t\treturn kPnach[mid].text;\n")
    out.write("\t\tif (c < 0)\n\t\t\tlo = mid + 1;\n\t\telse\n\t\t\thi = mid;\n\t}\n")
    out.write("\treturn nullptr;\n}\n")
print(f"gen-pnach: {len(entries)} patch files", file=sys.stderr)
